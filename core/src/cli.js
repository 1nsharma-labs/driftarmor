#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

import { scanTerraformDirectory } from './parser/hcl.js';
import { estimatePlanCost } from './cost/catalog.js';
import { detectInfrastructureDrift } from './drift/detector.js';
import { generateHtmlReport } from './report/html.js';

const args = process.argv.slice(2);
const command = args[0] || 'cost';

async function main() {
  if (args.includes('--help') || args.includes('-h') || command === 'help') {
    printHelp();
    process.exit(0);
  }

  if (args.includes('--version') || args.includes('-v')) {
    console.log('driftarmor v1.0.0 (1nsharma-labs)');
    process.exit(0);
  }

  const targetPath = args[1] && !args[1].startsWith('--') ? args[1] : null;

  console.log(`
  ==============================================================
    🛡️  DriftArmor — Terraform Drift & Cost Firewall v1.0.0
    🏢  Organization: 1nsharma-labs
  ==============================================================
  `);

  const resources = scanTerraformDirectory(targetPath);
  const costAnalysis = estimatePlanCost(resources);
  const driftFindings = detectInfrastructureDrift(targetPath);

  if (command === 'cost') {
    printCostSummary(costAnalysis);
    process.exit(0);
  }

  if (command === 'drift') {
    printDriftSummary(driftFindings);
    process.exit(0);
  }

  if (command === 'report') {
    const outIndex = args.indexOf('--output');
    const outPath = outIndex !== -1 ? args[outIndex + 1] : 'driftarmor-report.html';
    const html = generateHtmlReport(costAnalysis, driftFindings);
    fs.writeFileSync(outPath, html, 'utf-8');
    console.log(`📊 Executive FinOps & Drift report generated: ${path.resolve(outPath)}`);
    printCostSummary(costAnalysis);
    process.exit(0);
  }

  if (command === 'pr-comment') {
    printMarkdownPRComment(costAnalysis, driftFindings);
    process.exit(0);
  }

  console.error(`Unknown command: ${command}`);
  printHelp();
  process.exit(1);
}

function printCostSummary(cost) {
  console.log(`
  💰 TERRAFORM PLANNED COST ESTIMATION:
  --------------------------------------------------------------
  💵 Total Planned Monthly Cost:   $${cost.totalMonthlyUSD.toFixed(2)} / month
  📅 Total Annualized Run-Rate:    $${cost.totalAnnualUSD.toFixed(2)} / year
  📦 Managed Cloud Resources:      ${cost.resourceCount} resources
  --------------------------------------------------------------
  `);

  console.log('  RESOURCE COST BREAKDOWN:');
  console.log('  ' + '-'.repeat(75));
  console.log('  RESOURCE NAME                   TYPE                 ACTION     MONTHLY');
  console.log('  ' + '-'.repeat(75));

  for (const r of cost.breakdown) {
    const name = (r.name.length > 30 ? r.name.slice(0, 27) + '...' : r.name).padEnd(30);
    const type = (r.type.length > 20 ? r.type.slice(0, 18) + '..' : r.type).padEnd(20);
    const act = r.action.toUpperCase().padEnd(10);
    const m = `$${r.monthlyUSD.toFixed(2)}/mo`;
    console.log(`  ${name}  ${type} ${act} ${m}`);
  }
  console.log('  ' + '-'.repeat(75));
  console.log('\n  Run `driftarmor report` to generate executive HTML dashboard.');
  console.log('  Run `driftarmor drift` to inspect out-of-band console modifications.\n');
}

function printDriftSummary(drifts) {
  console.log(`
  ⚠️  INFRASTRUCTURE DRIFT DETECTION:
  --------------------------------------------------------------
  Found ${drifts.length} unmanaged or out-of-band console modifications!
  --------------------------------------------------------------
  `);

  for (const d of drifts) {
    console.log(`  [${d.severity}] ${d.resource}`);
    console.log(`    Type: ${d.driftType}`);
    console.log(`    Diff: ${d.details}`);
    console.log(`    Fix:  ${d.remediation}\n`);
  }
}

function printMarkdownPRComment(cost, drifts) {
  console.log(`
### 🛡️ DriftArmor Pull Request Cloud Cost & Drift Impact

| Metric | Planned Impact |
| :--- | :--- |
| 💵 **Monthly Cost Delta** | **+$${cost.totalMonthlyUSD.toFixed(2)} / month** |
| 📅 **Annualized Cost Delta** | **+$${cost.totalAnnualUSD.toFixed(2)} / year** |
| 📦 **Resources Changed** | ${cost.resourceCount} resources |
| ⚠️ **Drift Incidents Found** | ${drifts.length} unmanaged drifts |

<details>
<summary><b>Resource Cost Breakdown</b></summary>

| Resource | Action | Monthly Cost | Annual Cost |
| :--- | :--- | :--- | :--- |
${cost.breakdown.map(r => `| \`${r.name}\` (${r.type}) | \`${r.action}\` | $${r.monthlyUSD.toFixed(2)}/mo | $${r.annualUSD.toFixed(2)}/yr |`).join('\n')}

</details>

*Report generated by [DriftArmor](https://github.com/1nsharma-labs/driftarmor) &bull; 1nsharma-labs*
  `);
}

function printHelp() {
  console.log(`
DriftArmor — The Open-Source Terraform Drift Detector & Cloud Cost Firewall

USAGE:
  driftarmor [command] [path] [flags]

COMMANDS:
  cost [path]                 Estimate monthly cost of Terraform resources (default)
  drift [path]                Detect unmanaged out-of-band cloud console drift
  report [path] [--output f]  Generate interactive executive HTML report
  pr-comment [path]           Output GitHub PR markdown comment for CI/CD
  help                        Show help information

FLAGS:
  --output, -o                Specify output report HTML path
  --version, -v               Show version
  --help, -h                  Show help
  `);
}

main().catch(err => {
  console.error('Fatal Error:', err);
  process.exit(1);
});
